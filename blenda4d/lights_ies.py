"""Starter light profiles (IES files) for the IES Light, made by this code: each one is a simple beam shape written
as a standard photometric text file into the user's data folder, so the file picker has something to start from.
They are part of Blenda 4D and share its licence. Any other .ies file can be picked as well."""
import math
import os

import bpy


def _cos_beam(power):
    """A round beam aimed straight down that narrows as the power goes up."""
    return lambda a: max(0.0, math.cos(math.radians(a))) ** power if a < 90 else 0.0


def _batwing(a):
    """Two lobes at about 35 degrees from straight down: lights a wide floor evenly."""
    if a >= 90:
        return 0.0
    return 0.25 + 0.75 * math.exp(-((a - 35.0) / 18.0) ** 2)


def _up_down(a):
    """Light going both up and down, little to the side, like a wall sconce."""
    return max(math.cos(math.radians(a)) ** 6, 0.6 * max(0.0, -math.cos(math.radians(a))) ** 6, 0.0)


PROFILES = (
    ("Narrow Downlight", _cos_beam(40)),
    ("Medium Downlight", _cos_beam(10)),
    ("Wide Flood", _cos_beam(2)),
    ("Batwing", _batwing),
    ("Up and Down", _up_down),
)


def folder():
    return bpy.utils.user_resource("DATAFILES", path=os.path.join("blenda4d", "ies"), create=True)


def text_of(name, shape, peak=1000.0, step=2.5):
    angles = [i * step for i in range(int(180 / step) + 1)]
    values = [peak * shape(a) for a in angles]
    lines = ["IESNA:LM-63-2002", "[TEST] Generated by Blenda 4D", "[MANUFAC] Blenda 4D starter profile",
             f"[LUMINAIRE] {name}", "TILT=NONE",
             f"1 -1 1 {len(angles)} 1 1 2 0 0 0", "1 1 0"]
    for chunk in (angles, [0.0], values):
        for i in range(0, len(chunk), 10):
            lines.append(" ".join(f"{v:.3f}" for v in chunk[i:i + 10]))
    return "\n".join(lines) + "\n"


def ensure_files():
    """Write the starter profiles if they are not there yet; returns the folder."""
    d = folder()
    for name, shape in PROFILES:
        path = os.path.join(d, name.replace(" ", "_") + ".ies")
        if not os.path.exists(path):
            try:
                with open(path, "w", encoding="ascii") as fh:
                    fh.write(text_of(name, shape))
            except OSError as ex:
                print("Blenda 4D: could not write light profile", path, ex)
    return d
